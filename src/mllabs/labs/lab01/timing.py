"""Подання часу навчання у таблицях порівнянь."""

from __future__ import annotations

#: Час навчання фолда залежить від завантаженості комп'ютера й від запуску до
#: запуску «гуляє» на десятки відсотків, тому в таблицях він округлюється до
#: десятих і позначається як орієнтовний: порівнювати можна лише порядок величин.
FOLD_TIME_COLUMN = "Час фолда, с (орієнт.)"


def approximate_seconds(seconds: float) -> str:
    """Форматує час до одного знака після коми.

    Повертається рядок, а не число: інакше спільний формат дробових чисел
    таблиці (``%.4f``) знову дописав би незначущі знаки (``0.8000``).
    """
    return f"{seconds:.1f}"
